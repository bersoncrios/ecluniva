import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
import { initializeApp, deleteApp } from 'firebase/app';
import { getAuth, connectAuthEmulator, signInWithEmailAndPassword, signOut } from 'firebase/auth';
import { getFirestore, connectFirestoreEmulator, collection, doc, addDoc, updateDoc, getDocs, serverTimestamp, terminate } from 'firebase/firestore';

const baseUrl=process.env.QUADREI_BASE_URL || process.env.SOCIETAS_BASE_URL || 'http://127.0.0.1:4200';
const chromePath=process.env.QUADREI_CHROME_PATH || process.env.SOCIETAS_CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const waitFor=async(predicate,message,timeout=15000)=>{const deadline=Date.now()+timeout;while(Date.now()<deadline){if(await predicate())return;await new Promise(resolve=>setTimeout(resolve,75));}assert.fail(message);};
const civilYear=()=>Number(new Intl.DateTimeFormat('en-US',{timeZone:'America/Araguaina',year:'numeric'}).format(new Date()));
const payload=name=>({name,birthDate:null,receivedDate:null,office:'Diácono',address:{postalCode:'',street:'',number:'',complement:'',neighborhood:'',city:'',state:''},phone:'',email:'',notes:'',status:'active',createdAt:serverTimestamp(),updatedAt:serverTimestamp()});

test('annual board persists roles by year, preserves members and remains isolated across societies', {timeout:180000},async t=>{
  assert.ok(['localhost','127.0.0.1'].includes(new URL(baseUrl).hostname));
  const unique=`board-${Date.now()}-${process.pid}`;
  const email=`${unique}@example.test`,password='BoardTest123!';
  const response=await fetch('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signUp?key=demo-key',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email,password,returnSecureToken:true})});
  const signup=await response.json();assert.equal(response.ok,true,'Start local Auth and Firestore emulators.');
  const app=initializeApp({apiKey:'demo-key',authDomain:'demo-societas.firebaseapp.com',projectId:'demo-societas'},unique);
  const auth=getAuth(app);connectAuthEmulator(auth,'http://127.0.0.1:9099',{disableWarnings:true});
  const database=getFirestore(app);connectFirestoreEmulator(database,'127.0.0.1',8080);
  await signInWithEmailAndPassword(auth,email,password);
  const societyName=`Diretoria A ${unique}`,secondName=`Diretoria B ${unique}`;
  const society=await addDoc(collection(database,'societies'),{ownerId:signup.localId,churchName:'Igreja Presbiteriana QA Diretoria',type:'UPH',name:societyName,createdAt:serverTimestamp(),updatedAt:serverTimestamp()});
  await addDoc(collection(database,'societies'),{ownerId:signup.localId,churchName:'Igreja Presbiteriana QA Diretoria',type:'SAF',name:secondName,createdAt:serverTimestamp(),updatedAt:serverTimestamp()});
  const ana=await addDoc(collection(database,'societies',society.id,'members'),payload('Ana Diretora'));
  const bruno=await addDoc(collection(database,'societies',society.id,'members'),payload('Bruno Histórico'));
  await updateDoc(bruno,{status:'inactive',updatedAt:serverTimestamp()});
  const browser=await chromium.launch({executablePath:chromePath,headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000}});const page=await context.newPage();
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  t.after(async()=>{await context.close();await browser.close();await signOut(auth);await terminate(database);await deleteApp(app);});
  await context.route('https://viacep.com.br/**',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({erro:true})}));
  await page.goto(baseUrl,{waitUntil:'domcontentloaded'});
  await page.getByText('Acesso de testes locais',{exact:true}).click();
  await page.getByLabel('E-mail da conta de teste',{exact:true}).fill(email);
  await page.getByLabel('Senha da conta de teste',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Entrar na conta de teste',exact:true}).click();
  await page.getByRole('heading',{name:'Suas sociedades',exact:true}).waitFor();
  await page.getByRole('button').filter({has:page.getByText(societyName,{exact:true})}).click();
  await page.getByRole('heading',{name:'Visão geral',exact:true}).waitFor();
  await page.locator('.sidebar').getByRole('button',{name:'Diretoria',exact:true}).click();
  const year=civilYear();
  const boardTitle=value=>page.getByRole('heading',{name:`Diretoria ${value}`,exact:true});
  await boardTitle(year).waitFor();
  const chooseYear=async value=>{await page.getByLabel('Ano da diretoria',{exact:true}).fill(String(value));await page.getByRole('button',{name:'Ver diretoria',exact:true}).click();await boardTitle(value).waitFor();};
  await page.getByRole('button',{name:'Adicionar à diretoria',exact:true}).first().click();
  await page.getByLabel('Membro',{exact:true}).selectOption(ana.id);
  await page.getByLabel('Cargo na diretoria',{exact:true}).fill('Presidente');
  await page.getByRole('button',{name:'Salvar participação',exact:true}).click();
  await page.getByRole('button',{name:'Editar cargo de Ana Diretora',exact:true}).waitFor();
  let stored=await getDocs(collection(database,'societies',society.id,'boardAssignments'));
  assert.equal(stored.size,1);assert.equal(stored.docs[0].data().year,year);
  await page.getByRole('button',{name:'Editar cargo de Ana Diretora',exact:true}).click();
  await page.getByLabel('Cargo na diretoria',{exact:true}).fill('Vice-presidente');
  await page.getByRole('button',{name:'Salvar participação',exact:true}).click();
  await waitFor(async()=>{const docs=await getDocs(collection(database,'societies',society.id,'boardAssignments'));return docs.size===1&&docs.docs[0].data().role==='Vice-presidente';},'Role edit duplicated or failed to update assignment');
  await page.getByRole('button',{name:'Editar cargo de Ana Diretora',exact:true}).click();
  await page.getByLabel('Cargo na diretoria',{exact:true}).fill('Presidente');
  await page.getByRole('button',{name:'Salvar participação',exact:true}).click();
  await page.getByText('Participação salva.',{exact:true}).waitFor();
  await chooseYear(year+1);
  await page.getByRole('button',{name:'Adicionar à diretoria',exact:true}).first().click();
  await page.getByLabel('Membro',{exact:true}).selectOption(ana.id);
  await page.getByLabel('Cargo na diretoria',{exact:true}).fill('Tesoureiro');
  await page.getByRole('button',{name:'Salvar participação',exact:true}).click();
  await page.getByRole('button',{name:'Editar cargo de Ana Diretora',exact:true}).waitFor();
  await chooseYear(year);
  await page.getByText('Presidente',{exact:true}).waitFor();
  assert.equal(await page.getByText('Tesoureiro',{exact:true}).count(),0);
  await page.getByRole('button',{name:'Adicionar à diretoria',exact:true}).first().click();
  await page.getByLabel('Membro',{exact:true}).selectOption(bruno.id);
  await page.getByLabel('Cargo na diretoria',{exact:true}).fill('Secretário de atividades');
  await page.getByRole('button',{name:'Salvar participação',exact:true}).click();
  await page.getByRole('button',{name:'Editar cargo de Bruno Histórico',exact:true}).waitFor();
  await page.getByText('Inativo no rol atual',{exact:true}).waitFor();
  for(const width of [320,390,1440]) {
    await page.setViewportSize({width,height:900});
    const dimensions=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
    assert.ok(dimensions.scroll<=dimensions.client+1,`Board overflows ${width}px`);
    if(width<1024) assert.equal(await page.locator('.mobile-nav').getByRole('button').count(),6);
  }
  await mkdir('artifacts/browser',{recursive:true});
  await page.screenshot({path:`artifacts/browser/${unique}-desktop.png`,fullPage:true});
  await page.setViewportSize({width:390,height:900});
  await page.screenshot({path:`artifacts/browser/${unique}-mobile.png`,fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.reload({waitUntil:'domcontentloaded'});
  await page.getByRole('heading',{name:'Suas sociedades',exact:true}).waitFor();
  await page.getByRole('button').filter({has:page.getByText(societyName,{exact:true})}).click();
  await page.locator('.sidebar').getByRole('button',{name:'Diretoria',exact:true}).click();
  await page.getByRole('button',{name:'Editar cargo de Bruno Histórico',exact:true}).waitFor();
  await page.getByRole('button',{name:'Remover Ana Diretora da diretoria',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Cancelar',exact:true}).click();
  assert.equal((await getDocs(collection(database,'societies',society.id,'boardAssignments'))).size,3);
  await page.getByRole('button',{name:'Remover Ana Diretora da diretoria',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Remover da diretoria',exact:true}).click();
  await page.getByText('Participação removida da diretoria.',{exact:true}).waitFor();
  await waitFor(async()=>await page.getByRole('button',{name:'Editar cargo de Ana Diretora',exact:true}).count()===0,'Removed participation remained in current year');
  stored=await getDocs(collection(database,'societies',society.id,'boardAssignments'));
  assert.equal(stored.size,2);
  assert.ok(stored.docs.some(item=>item.data().memberId===ana.id&&item.data().year===year+1));
  assert.equal((await getDocs(collection(database,'societies',society.id,'members'))).size,2);
  await page.locator('.sidebar').getByRole('button',{name:'Membros',exact:true}).click();
  await page.locator('.members-table').getByRole('button',{name:'Editar Ana Diretora',exact:true}).click();
  await page.getByRole('button',{name:'Definir participação na diretoria',exact:true}).click();
  await boardTitle(year).waitFor();
  assert.equal(await page.getByLabel('Membro',{exact:true}).inputValue(),ana.id);
  await page.locator('.sidebar').getByRole('button',{name:'Trocar sociedade',exact:true}).click();
  await page.getByRole('heading',{name:'Suas sociedades',exact:true}).waitFor();
  await page.getByRole('button').filter({has:page.getByText(secondName,{exact:true})}).click();
  await page.locator('.sidebar').getByRole('button',{name:'Diretoria',exact:true}).click();
  await boardTitle(year).waitFor();
  assert.equal(await page.getByRole('button',{name:'Editar cargo de Bruno Histórico',exact:true}).count(),0);
  assert.equal(await page.getByText('Ana Diretora',{exact:true}).count(),0);
  assert.deepEqual(errors,[],'Unhandled board exceptions');
});

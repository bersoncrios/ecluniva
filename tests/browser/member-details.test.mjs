import { test } from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { initializeApp, deleteApp } from 'firebase/app';
import { getAuth, connectAuthEmulator, signInWithEmailAndPassword } from 'firebase/auth';
import { getFirestore, connectFirestoreEmulator, collection, addDoc, updateDoc, getDoc, serverTimestamp, terminate } from 'firebase/firestore';

const baseUrl=process.env.QUADREI_BASE_URL || 'http://127.0.0.1:4200';
test('member details preserve data and filters, support mobile, empty fields and editing', {timeout:120000}, async t=>{
  assert.ok(['localhost','127.0.0.1'].includes(new URL(baseUrl).hostname));
  const unique=`details-${Date.now()}`,email=`${unique}@example.test`,password='DetailsTest123!';
  const response=await fetch('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signUp?key=demo-key',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email,password,returnSecureToken:true})});
  const signup=await response.json();assert.equal(response.ok,true);
  const app=initializeApp({apiKey:'demo-key',projectId:'demo-societas',authDomain:'demo-societas.firebaseapp.com'},unique);
  const auth=getAuth(app);connectAuthEmulator(auth,'http://127.0.0.1:9099',{disableWarnings:true});
  const db=getFirestore(app);connectFirestoreEmulator(db,'127.0.0.1',8080);
  t.after(async()=>{await terminate(db);await deleteApp(app);});
  await signInWithEmailAndPassword(auth,email,password);
  const society=await addDoc(collection(db,'societies'),{ownerId:signup.localId,churchName:'Igreja Teste',type:'UPH',name:unique,createdAt:serverTimestamp(),updatedAt:serverTimestamp()});
  const member={name:'José Consulta',birthDate:'1980-05-10',receivedDate:'2020-03-15',office:'Diácono',address:{postalCode:'77000000',street:'Rua da Paz',number:'25',complement:'Casa B',neighborhood:'Centro',city:'Palmas',state:'TO'},phone:'63999999999',email:'jose@example.test',notes:'Observação de teste.\nSegunda linha.',status:'active',createdAt:serverTimestamp(),updatedAt:serverTimestamp()};
  const memberRef=await addDoc(collection(db,'societies',society.id,'members'),member);
  const inactive=await addDoc(collection(db,'societies',society.id,'members'),{...member,name:'Sem Dados',birthDate:null,receivedDate:null,office:'',address:{postalCode:'',street:'',number:'',complement:'',neighborhood:'',city:'',state:''},phone:'',email:'',notes:'',status:'active'});
  await updateDoc(inactive,{status:'inactive',updatedAt:serverTimestamp()});
  const before=(await getDoc(memberRef)).data();
  const browser=await chromium.launch({executablePath:process.env.QUADREI_CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
  t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(baseUrl);
  await page.getByText('Acesso de testes locais',{exact:true}).click();
  await page.getByLabel('E-mail da conta de teste',{exact:true}).fill(email);
  await page.getByLabel('Senha da conta de teste',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Entrar na conta de teste',exact:true}).click();
  await page.getByRole('button').filter({has:page.getByText(unique,{exact:true})}).click();
  await page.locator('.sidebar').getByRole('button',{name:'Membros',exact:true}).click();
  const search=page.getByRole('searchbox');await search.fill('José');
  const dialog=page.getByRole('dialog');
  for(const width of [1440,390,320]) {
    await page.setViewportSize({width,height:900});
    const container=width===1440?page.locator('.members-table'):page.locator('.mobile-members');
    const trigger=container.getByRole('button',{name:'Ver detalhes de José Consulta',exact:true});
    await trigger.click();await dialog.waitFor();
    const text=await dialog.textContent();
    for(const value of ['José Consulta','10/05/1980','15/03/2020','Diácono','Rua da Paz','25','Casa B','Centro','Palmas','TO','77000000','63999999999','jose@example.test','Observação de teste.'])assert.ok(text.includes(value),value);
    assert.equal(await dialog.locator('input, textarea, select').count(),0);
    assert.ok(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth+1));
    if(width===1440)await page.keyboard.press('Escape');else await dialog.getByRole('button',{name:'Fechar',exact:true}).click();
    assert.equal(await search.inputValue(),'José');
    assert.equal(await trigger.evaluate(el=>el===document.activeElement),true);
  }
  assert.deepEqual((await getDoc(memberRef)).data(),before);
  await page.locator('.mobile-members').getByRole('button',{name:'Ver detalhes de José Consulta',exact:true}).click();
  await dialog.getByRole('button',{name:'Editar cadastro',exact:true}).click();
  await page.getByRole('heading',{name:'Editar cadastro',exact:true}).waitFor();
  assert.equal(await page.getByLabel('Nome completo obrigatório',{exact:true}).inputValue(),'José Consulta');
  await page.getByRole('button',{name:'Cancelar',exact:true}).click();
  await page.locator('#status').selectOption('inactive');await search.fill('Sem Dados');
  await page.locator('.mobile-members').getByRole('button',{name:'Ver detalhes de Sem Dados',exact:true}).click();
  await dialog.waitFor();assert.ok((await dialog.textContent()).includes('Inativo'));
  assert.ok((await dialog.textContent()).includes('Não informada'));
  assert.ok((await dialog.textContent()).includes('Nenhuma observação registrada.'));
  await dialog.getByRole('button',{name:'Fechar',exact:true}).click();
  assert.deepEqual(errors,[]);
});

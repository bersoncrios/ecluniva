import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';
import { initializeApp, deleteApp } from 'firebase/app';
import { getAuth, connectAuthEmulator, signInWithEmailAndPassword, signOut } from 'firebase/auth';
import { getFirestore, connectFirestoreEmulator, collection, doc, addDoc, setDoc, updateDoc, getDoc, getDocs, serverTimestamp, terminate } from 'firebase/firestore';

const baseUrl=process.env.QUADREI_BASE_URL || process.env.SOCIETAS_BASE_URL || 'http://127.0.0.1:4200';
const chromePath=process.env.QUADREI_CHROME_PATH || process.env.SOCIETAS_CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const waitFor=async(predicate,message,timeout=20000)=>{const deadline=Date.now()+timeout;while(Date.now()<deadline){if(await predicate())return;await new Promise(resolve=>setTimeout(resolve,100));}assert.fail(message);};
const civilDate=()=>{const parts=new Intl.DateTimeFormat('en-CA',{timeZone:'America/Araguaina',year:'numeric',month:'2-digit',day:'2-digit'}).formatToParts(new Date());return ['year','month','day'].map(key=>parts.find(part=>part.type===key).value).join('-');};
const payload=(name,status='active')=>({name,birthDate:null,receivedDate:null,office:'',address:{postalCode:'',street:'',number:'',complement:'',neighborhood:'',city:'',state:''},phone:'',email:'',notes:'',status,createdAt:serverTimestamp(),updatedAt:serverTimestamp()});

// Tests use local Firebase only. Real attendance and immutable snapshots are
// asserted from persisted documents rather than a mocked service.
test('plenaries enforce civil-day attendance, preserve annual officers and issue an immutable PDF', {timeout:240000},async t=>{
  assert.ok(['localhost','127.0.0.1'].includes(new URL(baseUrl).hostname));
  const unique=`minutes-${Date.now()}-${process.pid}`;
  const email=`${unique}@example.test`,password='MinutesTest123!';
  const response=await fetch('http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts:signUp?key=demo-key',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email,password,returnSecureToken:true})});
  const signup=await response.json();assert.equal(response.ok,true,'Start local Auth/Firestore emulators.');
  const app=initializeApp({apiKey:'demo-key',authDomain:'demo-societas.firebaseapp.com',projectId:'demo-societas'},unique);
  const auth=getAuth(app);connectAuthEmulator(auth,'http://127.0.0.1:9099',{disableWarnings:true});
  const database=getFirestore(app);connectFirestoreEmulator(database,'127.0.0.1',8080);
  await signInWithEmailAndPassword(auth,email,password);
  const societyName=`Plenárias ${unique}`;
  const society=await addDoc(collection(database,'societies'),{ownerId:signup.localId,churchName:'Igreja Presbiteriana QA Plenárias',type:'UPH',name:societyName,createdAt:serverTimestamp(),updatedAt:serverTimestamp()});
  const ana=await addDoc(collection(database,'societies',society.id,'members'),payload('Ana Presidente'));
  const bruno=await addDoc(collection(database,'societies',society.id,'members'),payload('Bruno Secretário'));
  const inactive=await addDoc(collection(database,'societies',society.id,'members'),payload('Carlos Inativo'));
  await updateDoc(inactive,{status:'inactive',updatedAt:serverTimestamp()});
  const today=civilDate(),year=Number(today.slice(0,4));
  const future=new Date(today+'T12:00:00Z');future.setUTCDate(future.getUTCDate()+1);
  const futureDate=future.toISOString().slice(0,10);
  for(const [member,role] of [[ana,'Presidente'],[bruno,'1º Secretário']])await setDoc(doc(database,'societies',society.id,'boardAssignments',`${year}_${member.id}`),{year,memberId:member.id,role,createdAt:serverTimestamp(),updatedAt:serverTimestamp()});
  await setDoc(doc(database,'societies',society.id,'boardAssignments',`${year-1}_${bruno.id}`),{year:year-1,memberId:bruno.id,role:'Tesoureiro',createdAt:serverTimestamp(),updatedAt:serverTimestamp()});
  const browser=await chromium.launch({executablePath:chromePath,headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
  const page=await context.newPage();const errors=[];page.on('pageerror',error=>errors.push(error.message));
  t.after(async()=>{await context.close();await browser.close();await signOut(auth);await terminate(database);await deleteApp(app);});
  await mkdir('artifacts/browser',{recursive:true});
  await page.goto(baseUrl,{waitUntil:'domcontentloaded'});
  await page.getByText('Acesso de testes locais',{exact:true}).click();
  await page.getByLabel('E-mail da conta de teste',{exact:true}).fill(email);
  await page.getByLabel('Senha da conta de teste',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Entrar na conta de teste',exact:true}).click();
  const selectSociety=async()=>{await page.getByRole('heading',{name:'Suas sociedades',exact:true}).waitFor();await page.getByRole('button').filter({has:page.getByText(societyName,{exact:true})}).click();await page.getByRole('heading',{name:'Visão geral',exact:true}).waitFor();await page.locator('.sidebar').getByRole('button',{name:'Atas e plenárias',exact:true}).click();await page.getByRole('heading',{name:'Atas e plenárias',exact:true}).waitFor();};
  await selectSociety();
  const editor=page.locator('.minute-form');
  const schedule=async date=>{await page.getByRole('button',{name:'Agendar plenária',exact:true}).click();await page.getByLabel('Data civil da plenária',{exact:true}).fill(date);await page.getByLabel('Horário previsto',{exact:true}).fill('19:00');await page.getByLabel('Local da reunião',{exact:true}).fill('Casa do irmão João');await page.getByLabel('Endereço completo do local da reunião',{exact:true}).fill('Rua da Comunidade, 25, Centro, Palmas, TO, CEP 77000-000');await page.getByRole('button',{name:'Salvar agendamento',exact:true}).click();await waitFor(async()=>await page.locator('.minute-card').count()===(date===futureDate?1:2),'Scheduled plenary did not persist');};
  const card=number=>page.locator('.minute-card').filter({has:page.getByRole('heading',{name:new RegExp(`^Ata ${String(number).padStart(3,'0')} ·`)})});
  await schedule(futureDate);
  await card(1).getByRole('button',{name:'Abrir plenária',exact:true}).click();
  await editor.getByText(/Lista de presença indisponível/).waitFor();
  const anaPresence=editor.getByRole('checkbox',{name:'Presença de Ana Presidente',exact:true});
  await anaPresence.waitFor();assert.equal(await anaPresence.isDisabled(),true);
  assert.equal(await editor.getByRole('button',{name:'Receber e incluir na chamada',exact:true}).isDisabled(),true);
  await page.screenshot({path:`artifacts/browser/${unique}-future-blocked.png`,fullPage:true});
  const futureMinutes=await getDocs(collection(database,'societies',society.id,'minutes'));
  assert.equal(futureMinutes.size,1);assert.deepEqual(futureMinutes.docs[0].data().attendance,[]);
  await schedule(today);
  // New Year's Eve can place the future meeting in another annual counter.
  const todayStored=(await getDocs(collection(database,'societies',society.id,'minutes'))).docs.find(item=>item.data().date===today);
  assert.ok(todayStored);const number=todayStored.data().number;
  const todayCard=page.locator('.minute-card').filter({has:page.getByRole('heading',{name:`Ata ${String(number).padStart(3,'0')} · Ordinária`,exact:true})});
  await todayCard.getByRole('button',{name:'Abrir plenária',exact:true}).click();
  await waitFor(()=>anaPresence.isEnabled(),'Today attendance did not open');
  assert.equal(await editor.getByRole('checkbox',{name:'Presença de Carlos Inativo',exact:true}).count(),0);
  await editor.getByText(`Diretoria ${year} · Presidente`,{exact:true}).waitFor();
  await editor.getByText(`Diretoria ${year} · 1º Secretário`,{exact:true}).waitFor();
  assert.equal(await editor.getByText(/Tesoureiro/).count(),0);
  await editor.getByLabel('Buscar sócio',{exact:true}).fill('Ana');
  assert.equal(await editor.getByRole('checkbox').count(),1);
  await anaPresence.check();await editor.getByLabel('Buscar sócio',{exact:true}).fill('');
  await editor.getByRole('checkbox',{name:'Presença de Bruno Secretário',exact:true}).check();
  assert.equal(await editor.getByLabel('Presidente da sessão',{exact:true}).inputValue(),ana.id);
  assert.equal(await editor.getByLabel('Secretário redator',{exact:true}).inputValue(),bruno.id);
  await editor.getByText('2 presentes de 2 sócios ativos',{exact:true}).waitFor();
  await editor.getByRole('button',{name:'Salvar rascunho e chamada',exact:true}).click();
  await page.getByText('Rascunho e chamada salvos.',{exact:true}).waitFor();
  await editor.getByLabel('Nome completo',{exact:true}).fill('Débora Admitida');
  await editor.getByRole('button',{name:'Receber e incluir na chamada',exact:true}).click();
  await page.getByText('Sócio recebido, cadastrado e incluído entre os presentes.',{exact:true}).waitFor();
  await editor.getByText('3 presentes de 3 sócios ativos',{exact:true}).waitFor();
  const memberDocs=await getDocs(collection(database,'societies',society.id,'members'));
  const admitted=memberDocs.docs.find(item=>item.data().name==='Débora Admitida');
  assert.ok(admitted);assert.equal(admitted.data().receivedDate,today);assert.equal(admitted.data().status,'active');
  await editor.locator('#draft-convocation').selectOption('segunda');
  for(const [id,value] of Object.entries({startTime:'19:00',devotionalTime:'19:05',scripture:'Salmo 23',preacher:'Ana Presidente',openingPrayer:'Bruno Secretário',hymn:'Hino oficial da UPH',endTime:'21:00',closingPrayer:'Débora Admitida'}))await editor.locator(`#draft-${id}`).fill(value);
  const deliberations='Foi aprovada, por unanimidade, a contribuição destinada às atividades da sociedade. A diretoria apresentou o planejamento anual e foram deliberadas as ações de visitação e assistência aos sócios. '.repeat(32);
  await editor.locator('#draft-deliberations').fill(deliberations);
  assert.equal(await editor.locator('input[type="file"]').count(),0);
  const preview=page.locator('.minute-paper');
  assert.ok((await preview.textContent()).includes('3 sócios'));
  assert.ok((await preview.textContent()).includes('Débora Admitida'));
  assert.ok((await preview.textContent()).includes('Salmo 23'));
  await editor.getByRole('button',{name:'Salvar rascunho e chamada',exact:true}).click();
  await page.getByText('Rascunho e chamada salvos.',{exact:true}).waitFor();
  const persisted=(await getDoc(todayStored.ref)).data();
  assert.equal(persisted.attendance.length,3);assert.equal(persisted.presidentId,ana.id);assert.equal(persisted.secretaryId,bruno.id);
  assert.equal(persisted.attendance.find(person=>person.memberId===ana.id).role,'Presidente');
  assert.equal(persisted.deliberations,deliberations);
  for(const width of [320,390,1440]) {
    await page.setViewportSize({width,height:900});
    const dimensions=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
    assert.ok(dimensions.scroll<=dimensions.client+1,`Minutes overflow at ${width}px (${dimensions.scroll}/${dimensions.client})`);
    await page.screenshot({path:`artifacts/browser/${unique}-${width}.png`,fullPage:true});
  }
  await page.reload({waitUntil:'domcontentloaded'});await selectSociety();
  await todayCard.getByRole('button',{name:'Abrir plenária',exact:true}).click();
  await editor.getByText('3 presentes de 3 sócios ativos',{exact:true}).waitFor();
  assert.equal(await editor.locator('#draft-deliberations').inputValue(),deliberations);
  assert.equal(await editor.getByLabel('Presidente da sessão',{exact:true}).inputValue(),ana.id);
  await editor.getByRole('button',{name:'Lavrar e concluir ata',exact:true}).click();
  await page.getByRole('dialog',{name:'Lavrar e concluir a ata?',exact:true}).waitFor();
  await page.getByRole('dialog').getByRole('button',{name:'Confirmar lavratura',exact:true}).click();
  await page.getByText('Ata lavrada. O documento e o histórico de presença foram congelados.',{exact:true}).waitFor();
  assert.equal(await editor.getByRole('checkbox').count(),0);
  assert.equal(await editor.getByRole('button',{name:'Salvar rascunho e chamada',exact:true}).count(),0);
  const concluded=(await getDoc(todayStored.ref)).data();
  assert.equal(concluded.status,'concluded');assert.equal(concluded.attendance.length,3);assert.ok(concluded.finalText.includes('3 sócios'));
  await assert.rejects(updateDoc(todayStored.ref,{deliberations:'Alteração indevida',updatedAt:serverTimestamp()}),/permission|denied/i);
  // Later member/board edits must not rewrite the concluded document or PDF source.
  await updateDoc(ana,{name:'Ana Nome Alterado',updatedAt:serverTimestamp()});
  await updateDoc(doc(database,'societies',society.id,'boardAssignments',`${year}_${ana.id}`),{role:'Tesoureiro',updatedAt:serverTimestamp()});
  const frozen=(await getDoc(todayStored.ref)).data();
  assert.deepEqual(frozen.attendance,concluded.attendance);assert.equal(frozen.finalText,concluded.finalText);
  await page.reload({waitUntil:'domcontentloaded'});await selectSociety();
  await todayCard.getByRole('button',{name:'Consultar ata',exact:true}).click();
  await editor.getByText('Ana Presidente — Presidente',{exact:true}).waitFor();
  assert.equal(await editor.getByText('Ana Nome Alterado',{exact:true}).count(),0);
  const downloading=page.waitForEvent('download',{timeout:60000});
  await editor.getByRole('button',{name:'Baixar PDF da ata',exact:true}).click();
  const download=await downloading;assert.equal(await download.failure(),null);
  const filename=path.resolve('artifacts/browser',`${unique}-${download.suggestedFilename()}`);await download.saveAs(filename);
  const pdf=await readFile(filename);assert.equal(pdf.subarray(0,5).toString(),'%PDF-');
  const pages=(pdf.toString('latin1').match(/\/Type\s*\/Page\b/g)||[]).length;
  assert.ok(pages>=2,`Expected multipage minutes, got ${pages}`);assert.ok(pdf.length>10000);
  await page.screenshot({path:`artifacts/browser/${unique}-concluded.png`,fullPage:true});
  assert.deepEqual(errors,[],'Unhandled minutes browser errors');
});
